"""Write Challenge.lean, the self-contained statement of the compared results, from the library sources.

The Challenge imports only Mathlib. It copies verbatim, in library order, every definition that the compared
declarations use, and then the compared theorems with their proofs replaced by `sorry`. Each block keeps the section
kind (`@[expose] public section`) and the `open` commands of its source file, and the Challenge imports the Mathlib
modules visible in those source files (their own imports, and what their library imports export), so that the
elaborated constants are the library's. Comparator (with comparator.json) then checks that the library proves these
statements about these definitions.

The library has no instances, so (unlike gaussian-quartics) no instance had to be named.

Run from the project directory: python3 scripts/make_challenge.py          (writes Challenge.lean)
                                python3 scripts/make_challenge.py --check  (checks that it is up to date)
"""
import os
import re
import sys

# (source file, section kind, open commands, declarations); a declaration is (name, mode), where mode is 'copy'
# (verbatim, with its value) or 'stmt' (a theorem, proof replaced by sorry).
SECTION = '@[expose] public section'
BLOCKS = [
    # The definitions used by the statements.
    ('ThreeFactorials/Basic.lean', SECTION, [],
     [('block', 'copy'), ('Solution', 'copy'), ('CongruentPoint', 'copy')]),
    ('ThreeFactorials/Bounds.lean', SECTION, ['open Finset'],
     [('intervalPrimes', 'copy'), ('exponent', 'copy')]),
    ('ThreeFactorials/Case26.lean', SECTION, [],
     [('integralPoints26', 'copy'), ('IntegralPoints26Complete', 'copy')]),
    ('ThreeFactorials/Classification.lean', SECTION, [],
     [('solutionsUpTo100', 'copy')]),
    ('ThreeFactorials/ForbiddenForms.lean', SECTION, ['open Finset'],
     [('ForbiddenForm', 'copy')]),
    ('ThreeFactorials/Pell26.lean', SECTION, ['open Pell'],
     [('BennettConsecutiveUnique', 'copy')]),
    # The compared results: Theorem 1.1 at a₃ = 26.
    ('ThreeFactorials/Basic.lean', SECTION, [],
     [('solution_iff_squarefree', 'stmt')]),
    ('ThreeFactorials/Case26.lean', SECTION, [],
     [('solution324_26', 'stmt'), ('solution2738_26', 'stmt'), ('integralPoints26_sound', 'stmt'),
      ('case26_iff_of_integral_points', 'stmt')]),
    ('ThreeFactorials/Pell26.lean', SECTION, ['open Pell'],
     [('quartic104006_no_solution', 'stmt'), ('solution26_remaining', 'stmt'), ('case26_iff_of_bennett', 'stmt')]),
    ('ThreeFactorials/Case26Final.lean', SECTION, ['open Finset'],
     [('unique_first_system', 'stmt'), ('unique_second_system', 'stmt'), ('case26_iff', 'stmt')]),
    # Theorem 1.1 for a₃ ≤ 100: the seven solutions, and the classification given its completeness.
    ('ThreeFactorials/Classification.lean', SECTION, [],
     [('solutionsUpTo100_sound', 'stmt'), ('theorem11_iff_of_completeness', 'stmt'),
      ('prime_support_counterexample', 'stmt'), ('auxiliary_quartic_six', 'stmt')]),
    # Theorem 1.2.
    ('ThreeFactorials/Bounds.lean', SECTION, ['open Finset'],
     [('theorem12a', 'stmt'), ('theorem12b_fraction', 'stmt'), ('theorem12b_odd', 'stmt')]),
    ('ThreeFactorials/IntervalPrimes.lean', SECTION, ['open Finset'],
     [('interval_card_ge_eleven', 'stmt')]),
    ('ThreeFactorials/ForbiddenForms.lean', SECTION, ['open Finset'],
     [('theorem12c_large', 'stmt'), ('theorem12c_of_classification', 'stmt')]),
]


HEADER = '''module

{imports}

/-!
# Products of three factorials: statements

Results of A. Dujella, F. Najman, N. Saradha, T. N. Shorey, *Products of three factorials*, Publ. Math. Debrecen 85
(2014), 123–130 (doi:10.5486/PMD.2014.5835). Generated by `scripts/make_challenge.py` from the library sources: the
definitions that the statements use, copied verbatim, then the statements, with their proofs replaced by `sorry`.

`Solution a n` is the equation a!(a − 3)!n! = y² of Theorem 1.1 (with a = a₁, n = a₃), with a − 3 > n > 1.

* Theorem 1.1 at a₃ = 26, unconditionally: `case26_iff` (a₁ ∈ {{324, 2738}}), with the two solutions
  `solution324_26`, `solution2738_26`, the reduction to squarefree systems `solution_iff_squarefree`,
  `solution26_remaining`, `quartic104006_no_solution`, and the two remaining systems `unique_first_system`,
  `unique_second_system`. Two alternative routes take an unproved assertion as a hypothesis:
  `case26_iff_of_integral_points` (completeness of the integral points on Y² = X³ − 104006²X, the table checked by
  `integralPoints26_sound`) and `case26_iff_of_bennett` (Bennett's uniqueness theorem).
* Theorem 1.1 for a₃ ≤ 100: the seven listed pairs are solutions (`solutionsUpTo100_sound`); the classification is
  `theorem11_iff_of_completeness`, which takes the completeness of the list as a hypothesis.
* Theorem 1.2: (a) `theorem12a`; (b) in a corrected form, `theorem12b_fraction` and `theorem12b_odd`; (c) for
  a₃ ≥ 101 `theorem12c_large`, and as stated, with its exceptions, `theorem12c_of_classification`, which takes the
  completeness of Theorem 1.1 as a hypothesis; the paper's observation h ≥ 11 for a₃ ≥ 101 is
  `interval_card_ge_eleven`.
* Two numerical checks against statements in the paper: `prime_support_counterexample` (a prime factor of a₁ can
  exceed a₃, as the proof of Theorem 1.2(b) assumes it cannot) and `auxiliary_quartic_six` (equation (8) has a
  positive solution at a₃ = 6, which the paper's list a₃ = 3, 4, 18 omits).
-/
'''

DECL = re.compile(r'^(@\[[^\]]*\] )?((noncomputable|private|protected) )*(theorem|lemma|def|abbrev|instance|inductive|'
                  r'structure)\b')
OTHER = re.compile(r'^(end|end .*|namespace .*|open .*|section.*|variable .*|set_option .*|-- .*|'
                   r'(@\[[^\]]*\] )?public section)$')


def blocks_of(text):
    """The top-level items of a Lean source text, each declaration with its docstring and attribute lines."""
    lines = text.split('\n')
    starts, pending, comment = [], None, False
    for i, line in enumerate(lines):
        if comment:
            comment = '-/' not in line
            continue
        if line.startswith('/--'):  # a docstring belongs to the declaration that follows it
            pending = i if pending is None else pending
            comment = '-/' not in line
        elif line.startswith('/-'):  # a module docstring or a comment
            starts.append(i)
            comment = '-/' not in line
        elif re.match(r'^@\[[^\]]*\]$', line) or re.match(r'^set_option .* in$', line):  # likewise
            pending = i if pending is None else pending
        elif DECL.match(line) or OTHER.match(line):
            starts.append(i if pending is None else pending)
            pending = None
    starts.append(len(lines))
    return ['\n'.join(lines[a:b]).rstrip() + '\n' for a, b in zip(starts, starts[1:])]


def find(text, name, where):
    """The declaration `name` (with its docstring and attributes) in a Lean source text."""
    pat = re.compile(r'^(@\[[^\]]*\] )?(noncomputable )?(theorem|def|abbrev|instance|inductive|structure) '
                     + re.escape(name) + r'(\s|$)', re.M)
    hits = [b for b in blocks_of(text) if pat.search(b)]
    if len(hits) != 1:
        raise SystemExit(f'{where}: {len(hits)} declarations named {name}')
    return hits[0]


def sorried(text, name):
    """Replace the proof after the statement's `:=` by `sorry`. None of the compared statements contains `:=`, so
    the first `:=` that ends a line, or is followed by `by` and the end of the line, ends the statement; a `:=` with
    a proof term on the same line is refused."""
    m = re.search(r':=( by)?[ \t]*\n', text)
    first = text.find(':=')
    if not m or m.start() != first:
        raise SystemExit(f'{name}: cannot find the end of the statement')
    return text[:m.start()] + ':= sorry\n'


def file_imports(path):
    """The imports of a source file, as (public, module) pairs."""
    return [(bool(m.group(1)), m.group(2)) for m in re.finditer(r'^(public )?import (\S+)\s*$', open(path).read(), re.M)]


def exported(module):
    """The Mathlib modules that a library module makes visible to its importers: its public imports, recursively."""
    out = []
    for public, mod in file_imports(module.replace('.', '/') + '.lean'):
        if public:
            out += [mod] if mod.startswith('Mathlib') else exported(mod)
    return out


def imports():
    """The Mathlib modules visible in the source files of the blocks: their own imports, and what their library
    imports export."""
    mods = []
    for path in dict.fromkeys(b[0] for b in BLOCKS):
        for _, mod in file_imports(path):
            for m in [mod] if mod.startswith('Mathlib') else exported(mod):
                if m not in mods:
                    mods.append(m)
    return '\n'.join(f'public import {m}' for m in mods)


def challenge():
    out = [HEADER.format(imports=imports())]
    for path, section, opens, decls in BLOCKS:
        out.append(f'\n{section}\n\nnamespace ThreeFactorials\n')
        out += [o + '\n' for o in opens]
        for name, mode in decls:
            text = find(open(path).read(), name, path)
            out.append('\n' + (text if mode == 'copy' else sorried(text, name)))
        out.append('\nend ThreeFactorials\n\nend\n')
    return ''.join(out)


if __name__ == '__main__':
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    text = challenge()
    if '--check' in sys.argv:
        ok = os.path.exists('Challenge.lean') and open('Challenge.lean').read() == text
        print('Challenge.lean is up to date' if ok else 'Challenge.lean is NOT up to date')
        sys.exit(0 if ok else 1)
    open('Challenge.lean', 'w').write(text)
    print(f'wrote Challenge.lean: {text.count(chr(10))} lines, {len(text.encode())} bytes')
