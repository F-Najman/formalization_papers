"""Write Challenge.lean, the self-contained statement of the compared results, from the library sources.

The Challenge imports only Mathlib. It copies verbatim, in library order, every definition and instance that the
compared declarations use, and then the compared declarations with their proofs or values replaced by `sorry`.
Each block keeps the section kind (`@[expose] public section` or `public section`) of its source file, and the
Challenge imports exactly the Mathlib modules that the library files import, so that the elaborated constants are
the library's. Comparator (with comparator.json) then checks that the library proves these statements about these
definitions.

Run from the project directory: python3 scripts/make_challenge.py          (writes Challenge.lean)
                                python3 scripts/make_challenge.py --check  (checks that it is up to date)
"""
import os
import re
import sys

# (source file, section kind, open commands, declarations); a declaration is (name, mode), where mode is 'copy'
# (verbatim, with its proof or value), 'stmt' (a theorem, proof replaced by sorry) or 'hole' (a definition whose
# value the Solution supplies: value replaced by sorry, listed in definition_names).
BLOCKS = [
    ('GaussianQuartics/GaussianCurves.lean', '@[expose] public section', [],
     [('GaussianRat', 'copy'), ('instFactNotIsSquareNegOne', 'copy'), ('I', 'copy')]),
    ('GaussianQuartics/FieldClassification.lean', '@[expose] public section', [],
     [('Trivial', 'copy'), ('ScaledPlusSolution', 'copy')]),
    ('GaussianQuartics/PointGroups.lean', 'public section', ['open WeierstrassCurve.Affine'],
     [('plusCurve', 'copy'), ('minusCurve', 'copy'), ('instIsEllipticPlusCurve', 'copy'),
      ('instIsEllipticMinusCurve', 'copy')]),
    ('GaussianQuartics.lean', '@[expose] public section', [],
     [('intI', 'copy'), ('Primitive', 'copy'), ('UnitChoice', 'copy')]),
    # The compared results.
    ('GaussianQuartics.lean', '@[expose] public section', [],
     [('theorem1i', 'stmt'), ('theorem1ii', 'stmt'), ('theorem2_plus', 'stmt'), ('theorem2_minus', 'stmt'),
      ('gaussian_int_plus_i_iff', 'stmt')]),
    ('GaussianQuartics/FieldClassification.lean', '@[expose] public section', [],
     [('rat_minus_i_trivial', 'stmt'), ('rat_plus_i_iff', 'stmt'), ('rat_hilbert_plus', 'stmt'),
      ('rat_hilbert_minus', 'stmt')]),
    ('GaussianQuartics/PointGroups.lean', 'public section', [],
     [('plusPointGroup', 'hole'), ('minusPointGroup', 'hole')]),
]


HEADER = '''module

{imports}

/-!
# The Diophantine equation x⁴ ± y⁴ = iz² in Gaussian integers: statements

The results of F. Najman, *The Diophantine equation x⁴ ± y⁴ = iz² in Gaussian integers*, Amer. Math. Monthly 117
(2010), 637–641 (arXiv:1005.1528). Generated by `scripts/make_challenge.py` from the library sources: the definitions
and instances that the statements use, copied verbatim, then the statements, with their proofs replaced by `sorry`.

* Theorem 1(i): `theorem1i`. Theorem 1(ii), with its converse: `theorem1ii`; all nontrivial solutions, primitive or
  not: `gaussian_int_plus_i_iff`.
* Theorem 2 (Hilbert): `theorem2_plus`, `theorem2_minus`.
* The closing remark (the same results over ℚ(i)): `rat_minus_i_trivial`, `rat_plus_i_iff`, `rat_hilbert_plus`,
  `rat_hilbert_minus`.
* The groups of ℚ(i)-points used in the proofs, points at infinity included: E(ℚ(i)) ≅ ℤ/2 × ℤ/2 for
  `Y² = X³ + X` and ℤ/2 × ℤ/4 for `Y² = X³ − X`. These are the definitions `plusPointGroup` and `minusPointGroup`,
  whose values (additive isomorphisms) the Solution supplies; their types are the statements.

Three instances are copied with their proofs: `Fact (¬ IsSquare (-1 : ℚ))`, from which Mathlib makes
`QuadraticAlgebra ℚ (-1) 0` a field, and `IsElliptic` (nonzero discriminant) for the two curves.
-/
'''

DECL = re.compile(r'^(@\[[^\]]*\] )?((noncomputable|private|protected) )*(theorem|lemma|def|abbrev|instance)\b')
OTHER = re.compile(r'^(end|end .*|namespace .*|open .*|section.*|variable .*|-- .*|(@\[[^\]]*\] )?public section)$')


def blocks_of(text):
    """The top-level items of a Lean source text, each declaration with its docstring and attribute lines."""
    lines = text.split('\n')
    starts, pending, comment = [], None, False
    for i, line in enumerate(lines):
        if comment:
            comment = '-/' not in line
            continue
        if line.startswith('/--'):  # a docstring belongs to the declaration that follows it
            pending = i if pending is None else pending
            comment = '-/' not in line
        elif line.startswith('/-'):  # a module docstring or a comment
            starts.append(i)
            comment = '-/' not in line
        elif re.match(r'^@\[[^\]]*\]$', line):  # an attribute line, likewise
            pending = i if pending is None else pending
        elif DECL.match(line) or OTHER.match(line):
            starts.append(i if pending is None else pending)
            pending = None
    starts.append(len(lines))
    return ['\n'.join(lines[a:b]).rstrip() + '\n' for a, b in zip(starts, starts[1:])]


def find(text, name, where):
    """The declaration `name` (with its docstring and attributes) in a Lean source text."""
    pat = re.compile(r'^(@\[[^\]]*\] )?(noncomputable )?(theorem|def|abbrev|instance) ' + re.escape(name) + r'\b', re.M)
    hits = [b for b in blocks_of(text) if pat.search(b)]
    if len(hits) != 1:
        raise SystemExit(f'{where}: {len(hits)} declarations named {name}')
    return hits[0]


def sorried(text, name):
    """Replace the proof or value after the declaration's top-level `:=` by `sorry`."""
    m = re.search(r':=( by)?\s*\n', text)
    if not m:
        raise SystemExit(f'{name}: cannot find the end of the statement')
    return text[:m.start()] + ':= sorry\n'


def file_imports(path):
    """The imports of a source file, as (public, module) pairs."""
    return [(bool(m.group(1)), m.group(2)) for m in re.finditer(r'^(public )?import (\S+)\s*$', open(path).read(), re.M)]


def exported(module):
    """The Mathlib modules that a library module makes visible to its importers: its public imports, recursively."""
    out = []
    for public, mod in file_imports(module.replace('.', '/') + '.lean'):
        if public:
            out += [mod] if mod.startswith('Mathlib') else exported(mod)
    return out


def imports():
    """The Mathlib modules visible in the source files of the blocks: their own imports, and what their library
    imports export. Modules that the library imports only privately elsewhere are left out, since they change
    instance resolution (for instance, a private import of Mathlib.NumberTheory.FLT.Four brings the field structure
    of ZMod 2)."""
    mods = []
    for path in dict.fromkeys(b[0] for b in BLOCKS):
        for _, mod in file_imports(path):
            for m in [mod] if mod.startswith('Mathlib') else exported(mod):
                if m not in mods:
                    mods.append(m)
    return '\n'.join(f'public import {m}' for m in mods)


def challenge():
    out = [HEADER.format(imports=imports())]
    for path, section, opens, decls in BLOCKS:
        out.append(f'\n{section}\n\nnamespace GaussianQuartics\n')
        out += [o + '\n' for o in opens]
        for name, mode in decls:
            text = find(open(path).read(), name, path)
            out.append('\n' + (text if mode == 'copy' else sorried(text, name)))
        out.append('\nend GaussianQuartics\n\nend\n')
    return ''.join(out)


if __name__ == '__main__':
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    text = challenge()
    if '--check' in sys.argv:
        ok = os.path.exists('Challenge.lean') and open('Challenge.lean').read() == text
        print('Challenge.lean is up to date' if ok else 'Challenge.lean is NOT up to date')
        sys.exit(0 if ok else 1)
    open('Challenge.lean', 'w').write(text)
    print(f'wrote Challenge.lean: {text.count(chr(10))} lines, {len(text.encode())} bytes')
